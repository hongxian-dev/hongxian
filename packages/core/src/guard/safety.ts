/** 确认行（勾选框文案）：默认必须是空的，不做默认勾选 */
export const SAFETY_ACK_LABEL = '我读完了，并且明白平台不为对方的身份做任何担保';

/** 未确认时返回的完整拦截块（宿主 UI 差异大，只依赖纯文本） */
export function safetyAckBlock(): string {
  return (
    SAFETY_NOTICE_TEXT +
    '\n\n' +
    `[ ] ${SAFETY_ACK_LABEL}\n\n` +
    '（确认以上内容、并且明白平台不为对方的身份做任何担保，' +
    '请调用 interview(action="ack")。这不是报错，是建画像前的最后一道确认。）'
  );
}

/**
 * 版本比较：本地 ack 的版本与当前文案版本是否一致。
 * 用"不相等就要重看"而不是语义化版本比较——文案改动没有"向后兼容"这回事。
 */
export function safetyAckSatisfied(ackedVersion: string | null | undefined): boolean {
  return !!ackedVersion && ackedVersion === SAFETY_NOTICE_VERSION;
}
